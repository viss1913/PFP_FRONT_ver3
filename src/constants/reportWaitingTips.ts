/** Смена справки при ожидании (модалка отчёта, страница превью). */
export const REPORT_WAITING_TIP_INTERVAL_MS = 5_000;

export function useRotatingWaitingTip(active: boolean, tips: readonly string[], intervalMs: number): string {
    const [index, setIndex] = useState(0);
    const len = tips.length;

    useLayoutEffect(() => {
        if (!active || len === 0) return;

        setIndex(Math.floor(Math.random() * len));

        const id = window.setInterval(() => {
            setIndex((i) => (i + 1) % len);
        }, intervalMs);

        return () => window.clearInterval(id);
    }, [active, intervalMs, len]);

    if (!active || len === 0) return '';
    return tips[index % len] ?? '';
}
